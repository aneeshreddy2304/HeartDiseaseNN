from sklearn.inspection import permutation_importance
from sklearn.base import BaseEstimator, ClassifierMixin
import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

#Wrap Keras model for sklearn compatibility
class KerasWrapper(BaseEstimator, ClassifierMixin):
    def __init__(self, model):
        self.model = model

    def fit(self, X, y=None):
        return self

    def predict(self, X):
        y_pred_prob = self.model.predict(X)
        return (y_pred_prob > 0.5).astype(int).flatten()

wrapped_model = KerasWrapper(model)

#Compute permutation importance
perm_importance = permutation_importance(
    wrapped_model, X_val, y_val, scoring='accuracy', n_repeats=10, random_state=42
)

#Converting to Dataframe and sort by importance
feature_importance_df = pd.DataFrame({
    'Feature': X_val.columns,
    'Importance': perm_importance.importances_mean
}).sort_values(by='Importance', ascending=False)

